#!/usr/bin/env python3
"""Lockstep equivalence check (E3) of the GVM programs generated from a GRAFCET description.

The programs generated by grafcet2gvm.py (Python, C++, and, with --openplc, ST compiled with matiec as OpenPLC
Runtime version 3 compiles it) are stepped together with the reference, tick by tick, on the same inputs.  The
reference is the explicit-state model of nusmv/grafcet2smv.py, whose transition relation equals that of the
generated NuSMV model on every reachable state (grafcet2smv.py --selfcheck).  After every tick, the situation, the
stability flag, and the outputs of each program are compared with the reference; E3 counts the ticks with any
difference.  The programs are equivalent to the reference on the tested inputs when E3 = 0 for each of them.

Coverage:
  1. exhaustive over one tick: every reachable stable situation of the reference x every input combination, each
     reached from the initial situation by a shortest input path (the ticks of the path are compared too);
  2. random input sequences from the initial situation (--seqs x --len ticks, seed 20261113).
Negative controls: programs generated with a seeded fault (grafcet2gvm.py --fault, or a receptivity changed in the
description) must give E3 > 0, otherwise the check is not sensitive.

  python3 e3_check.py ../nusmv/tank_reference.json --openplc OPENPLC_V3_DIR --log e3_log.txt
  python3 e3_check.py ../nusmv/tank_reference.json             # Python and C++ only (for example in Colab)
"""
import argparse
import collections
import copy
import hashlib
import importlib.util
import json
import os
import platform
import random
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True   # keep the kit folders free of __pycache__
sys.path.insert(0, os.path.join(HERE, '..', 'nusmv'))
sys.path.insert(0, HERE)
import grafcet2smv as g2s  # noqa: E402
import grafcet2gvm as gen  # noqa: E402

SEED = 20261113


# ------------------------------------------------------------------ reference
class Reference:
    def __init__(self, spec):
        self.m = g2s.Model(spec).explore()
        self.spec = spec
        self.dom = self.m.domains

    def to_raw(self, vec):
        return tuple(d[v] if d != [False, True] else bool(v) for v, d in zip(vec, self.dom))

    def to_vec(self, combo):
        return tuple(d.index(v) if d != [False, True] else int(v) for v, d in zip(combo, self.dom))

    def run(self, seq):
        c, out = self.m.init, []
        for vec in seq:
            c, stable = self.m.evolve(c, self.to_raw(vec))
            e = {x: c[j] for j, x in enumerate(self.m.steps)}
            o = tuple(bool(self.m.ev(node, e)) for node in self.m.outputs.values())
            out.append((tuple(bool(b) for b in c), bool(stable), o))
        return out

    def paths(self):
        """Shortest input path (list of input vectors) from the initial situation to every reachable situation."""
        path = {self.m.init: []}
        queue = collections.deque([self.m.init])
        while queue:
            c = queue.popleft()
            for combo, c2 in zip(self.m.combos, self.m.nxt[c]):
                if c2 not in path:
                    path[c2] = path[c] + [self.to_vec(combo)]
                    queue.append(c2)
        return path


def tests(ref, seqs, length):
    vecs = [ref.to_vec(c) for c in ref.m.combos]
    paths = ref.paths()
    exhaustive = [paths[c] + [v] for c in ref.m.confs for v in vecs]
    rnd = random.Random(SEED)
    bias = {'start': 0.3, 'stop': 0.1}

    def draw():
        v = []
        for (n, d), dom in zip(ref.m.inputs, ref.dom):
            v.append(rnd.randrange(len(dom)) if dom != [False, True] else int(rnd.random() < bias.get(n, 0.5)))
        return tuple(v)
    random_seqs = [[draw() for _ in range(length)] for _ in range(seqs)]
    return exhaustive, random_seqs


# ------------------------------------------------------------------ legs
def run_py(gdir, name, suites):
    spec = importlib.util.spec_from_file_location(name + '_gvm', os.path.join(gdir, name + '_gvm.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    g = mod.GVM()
    res = []
    for seq in suites:
        g.reset()
        out = []
        for vec in seq:
            c, stable, o = g.tick(vec)
            out.append((tuple(bool(b) for b in c), bool(stable), tuple(bool(b) for b in o)))
        res.append(out)
    return res


def run_cpp(gdir, name, suites, work):
    exe = os.path.join(work, name + '_gvm')
    r = subprocess.run(['g++', '-std=c++17', '-O2', '-Wall', '-o', exe, os.path.join(gdir, name + '_gvm_main.cpp')],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError('g++: ' + (r.stdout + r.stderr)[-500:])
    lines = []
    for seq in suites:
        lines.append('R')
        lines += ['T ' + ' '.join(str(v) for v in vec) for vec in seq]
    p = subprocess.run([exe], input='\n'.join(lines) + '\n', capture_output=True, text=True, check=True)
    rows = p.stdout.split('\n')
    res, k = [], 0
    for seq in suites:
        out = []
        for _ in seq:
            sit, st, o = rows[k].split()
            k += 1
            out.append((tuple(ch == '1' for ch in sit), st == '1', tuple(ch == '1' for ch in o)))
        res.append(out)
    return res, (r.stderr.strip().count('warning'))


def run_st(gdir, name, suites, openplc, work):
    sys.path.insert(0, os.path.join(HERE, '..', 'exec'))
    spec = importlib.util.spec_from_file_location('scene_sim', os.path.join(HERE, '..', 'exec', 'scene_sim.py'))
    sim = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sim)
    text, note, _ = sim.compile_check.prepare(os.path.join(gdir, name + '_gvm.st'))
    if text is None:
        raise RuntimeError(note)
    plc = sim.PLC(text, openplc, work)
    io = json.load(open(os.path.join(gdir, name + '_gvm_io.json'), encoding='utf-8'))
    loc = io['located']
    ins = [loc['in_' + n] for n in io['inputs']]
    outs = [loc['out_' + n] for n in io['outputs']]
    sits = [loc['x_' + x] for x in io['steps']]
    st_loc = loc['out_stable']
    res = []
    for seq in suites:
        plc.reset()
        out = []
        for vec in seq:
            for a, v in zip(ins, vec):
                plc.set(a, v)
            plc.scan()
            out.append((tuple(bool(plc.get(a)) for a in sits), bool(plc.get(st_loc)), tuple(bool(plc.get(a)) for a in outs)))
        res.append(out)
    if plc.missing:
        raise RuntimeError('located variables not connected: %s' % sorted(plc.missing))
    return res, note


def compare(ref_out, leg_out):
    ticks = bad = 0
    first = None
    for k, (r_seq, l_seq) in enumerate(zip(ref_out, leg_out)):
        for t, (r, l) in enumerate(zip(r_seq, l_seq)):
            ticks += 1
            if r != l:
                bad += 1
                if first is None:
                    first = (k, t, r, l)
    return ticks, bad, first


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('model')
    ap.add_argument('--openplc', help='OpenPLC_v3 folder with matiec built (adds the ST program)')
    ap.add_argument('--out', default=os.path.join(HERE, 'generated'), help='folder for the generated programs')
    ap.add_argument('--seqs', type=int, default=200)
    ap.add_argument('--len', type=int, default=100)
    ap.add_argument('--log')
    a = ap.parse_args()
    lines = []

    def say(s=''):
        print(s)
        lines.append(s)

    spec = json.load(open(a.model, encoding='utf-8'))
    t0 = time.time()
    d, files = gen.generate(a.model, a.out)
    ref = Reference(spec)
    ex, rs = tests(ref, a.seqs, a.len)
    suites = ex + rs
    ref_out = [ref.run(s) for s in suites]
    n_ex = sum(len(s) for s in ex)
    n_rs = sum(len(s) for s in rs)
    say('E3 lockstep equivalence check: %s.json (description SHA-256 %s over %s), grafcet2gvm.py (SHA-256 %s)' % (
        d.name, gen.desc_sha(spec)[:16], ', '.join(gen.SEM_KEYS), sha(os.path.join(HERE, 'grafcet2gvm.py'))[:16]))
    say('reference: explicit-state model of nusmv/grafcet2smv.py; %d steps, %d transitions, K = %d micro-steps' % (
        len(d.steps), len(d.trans), d.K))
    say('coverage: (1) %d reachable stable situations x %d input combinations = %d one-tick tests from the initial '
        'situation (%d ticks with their paths); (2) %d random sequences x %d ticks = %d ticks (seed %d)' % (
            len(ref.m.confs), len(ref.m.combos), len(ex), n_ex, a.seqs, a.len, n_rs, SEED))
    say('generated programs: %s' % ', '.join('%s (SHA-256 %s)' % (f, sha(os.path.join(a.out, f))[:16]) for f in files))
    say('tools: Python %s; %s' % (platform.python_version(), subprocess.run(
        ['g++', '--version'], capture_output=True, text=True).stdout.splitlines()[0]))
    say()
    ok = True
    with tempfile.TemporaryDirectory() as work:
        legs = [('Python', lambda g: run_py(g, d.name, suites)),
                ('C++', lambda g: run_cpp(g, d.name, suites, work)[0])]
        if a.openplc:
            legs.append(('ST (matiec)', lambda g: run_st(g, d.name, suites, a.openplc, work)[0]))
        say('%-12s %10s %8s  %s' % ('program', 'ticks', 'E3', 'first difference'))
        for leg, fn in legs:
            out = fn(a.out)
            ticks, bad, first = compare(ref_out, out)
            ok = ok and bad == 0 and ticks == n_ex + n_rs
            say('%-12s %10d %8d  %s' % (leg, ticks, bad, '-' if first is None else 'test %d tick %d: reference %s, program %s'
                                       % first))
        say()
        say('negative controls (each must give E3 > 0):')
        mutated = copy.deepcopy(spec)
        tid = next(t['id'] for t in mutated['transitions'] if t['guard'] not in ('TRUE', 'FALSE'))
        old = next(t['guard'] for t in mutated['transitions'] if t['id'] == tid)
        for t in mutated['transitions']:
            if t['id'] == tid:
                t['guard'] = '!(%s)' % t['guard']
        controls = [('event read in every micro-step', dict(fault='event-level')),
                    ('forcing order dropped', dict(fault='no-forcing')),
                    ('receptivity of %s negated (%s)' % (tid, old), dict(spec=mutated))]
        for label, kw in controls:
            if kw.get('fault') == 'no-forcing' and not spec.get('forcing'):
                continue
            gdir = os.path.join(work, 'neg_' + str(abs(hash(label)) % 10 ** 8))
            gen.generate(a.model, gdir, kw.get('fault'), kw.get('spec'))
            row = []
            for leg, fn in legs:
                out = fn(gdir)
                _, bad, _ = compare(ref_out, out)
                row.append('%s %d' % (leg, bad))
                ok = ok and bad > 0
            say('  %-46s E3: %s' % (label, ', '.join(row)))
    say()
    say('result: %s (%.1f s)' % ('equivalent on all tested inputs; every negative control detected' if ok else
                                 'NOT EQUIVALENT or a negative control not detected', time.time() - t0))
    if a.log:
        open(a.log, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
